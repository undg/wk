func fixture(t *testing.T) string {
	t.Helper()
	root := t.TempDir()
	for _, args := range [][]string{
		{"init", "-q"}, {"config", "user.email", "metrics@example.invalid"}, {"config", "user.name", "metrics tests"},
	} {
		if _, err := git(root, args...); err != nil {
			t.Fatal(err)
		}
	}
	put(t, root, "go.mod", "module example.invalid/fixture\n\ngo 1.24.5\n")
	put(t, root, "first.go", "package fixture\nfunc First() int { return 1 }\n")
	put(t, root, "second.go", "package fixture\nfunc Second() int { return 2 }\n")
	commit(t, root)
	return root
}

func put(t *testing.T, root, name, content string) {
	t.Helper()
	path := filepath.Join(root, name)
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0644); err != nil {
		t.Fatal(err)
	}
}

func commit(t *testing.T, root string) {
	t.Helper()
	for _, args := range [][]string{{"add", "."}, {"commit", "-qm", "fixture"}} {
		if _, err := git(root, args...); err != nil {
			t.Fatal(err)
		}
	}
}

func expectScope(t *testing.T, root string, files []string, base string, all bool, want ...string) {
	t.Helper()
	got, _, err := selectFiles(root, files, base, all)
	if err != nil {
		t.Fatal(err)
	}
	if !slices.Equal(got, want) {
		t.Fatalf("scope = %q, want %q", got, want)
	}
}

func TestExactScopeAndPrecedence(t *testing.T) {
	root := fixture(t)
	put(t, root, "folder with space/third.go", "package third\n")
	files, err := parseFiles(`"folder with space/third.go" first.go`)
	if err != nil {
		t.Fatal(err)
	}
	for i, file := range files {
		files[i] = filepath.Join(root, file)
	}
	expectScope(t, root, files, "invalid-base", false, "first.go", "folder with space/third.go")
	expectScope(t, root, []string{filepath.Join(root, "second.go")}, "invalid-base", true, "second.go")
	for _, value := range []string{`"unterminated`, `""`} {
		if _, err := parseFiles(value); err == nil {
			t.Fatalf("accepted bad FILES %q", value)
		}
	}
}

func TestExactPathsAcceptAliasedParentDirectories(t *testing.T) {
	root := fixture(t)
	alias := filepath.Join(t.TempDir(), "alias")
	if err := os.Symlink(root, alias); err != nil {
		t.Fatal(err)
	}
	for _, repository := range []string{root, alias} {
		expectScope(t, repository, []string{filepath.Join(root, "first.go"), filepath.Join(alias, "second.go")}, "", false, "first.go", "second.go")
	}
	t.Chdir(alias)
	t.Setenv("FILES", "")
	t.Setenv("BASE", "")
	original := os.Args
	t.Cleanup(func() { os.Args = original })
	os.Args = []string{"metrics", "crap", "-file", "first.go", "-list"}
	if err := run(); err != nil {
		t.Fatal(err)
	}
	outside := fixture(t)
	escape := filepath.Join(root, "escape")
	if err := os.Symlink(outside, escape); err != nil {
		t.Fatal(err)
	}
	if _, err := exactPath(root, filepath.Join(escape, "first.go")); err == nil {
		t.Fatal("accepted aliased directory outside repository")
	}
}

func TestBranchScopeIncludesCommittedStagedDirtyAndUntrackedFiles(t *testing.T) {
	root := fixture(t)
	base, err := git(root, "rev-parse", "HEAD")
	if err != nil {
		t.Fatal(err)
	}
	put(t, root, "committed.go", "package fixture\n")
	commit(t, root)
	put(t, root, "staged.go", "package fixture\n")
	if _, err := git(root, "add", "staged.go"); err != nil {
		t.Fatal(err)
	}
	put(t, root, "first.go", "package fixture\n// unstaged\n")
	put(t, root, "untracked.go", "package fixture\n")
	put(t, root, "other_test.go", "package fixture\n")
	put(t, root, "generated.go", "// Code generated by metrics fixture. DO NOT EDIT.\npackage fixture\n")
	put(t, root, "vendor/lib.go", "package vendor\n")
	put(t, root, "testdata/example.go", "package example\n")
	put(t, root, ".private/secret.go", "package secret\n")
	put(t, root, "build/artifact.go", "package artifact\n")
	put(t, root, "ignored.go", "package fixture\n")
	put(t, root, ".gitignore", "ignored.go\n")
	expectScope(t, root, nil, base, false, "committed.go", "first.go", "staged.go", "untracked.go")
	expectScope(t, root, nil, "", true, "committed.go", "first.go", "second.go", "staged.go", "untracked.go")
}

func TestRenamesAndDeletionsUseCurrentPaths(t *testing.T) {
	root := fixture(t)
	if _, err := git(root, "mv", "first.go", "renamed.go"); err != nil {
		t.Fatal(err)
	}
	if err := os.Remove(filepath.Join(root, "second.go")); err != nil {
		t.Fatal(err)
	}
	expectScope(t, root, nil, "HEAD", false, "renamed.go")
}

func TestBranchScopeUsesMergeBaseNotBaseTip(t *testing.T) {
	root := fixture(t)
	if _, err := git(root, "branch", "feature"); err != nil {
		t.Fatal(err)
	}
	put(t, root, "base-only.go", "package fixture\n")
	commit(t, root)
	base, err := git(root, "rev-parse", "HEAD")
	if err != nil {
		t.Fatal(err)
	}
	if _, err := git(root, "checkout", "-q", "feature"); err != nil {
		t.Fatal(err)
	}
	put(t, root, "feature.go", "package fixture\n")
	commit(t, root)
	expectScope(t, root, nil, base, false, "feature.go")
}

func TestEmptyAndTestOnlyScopeNeverBroaden(t *testing.T) {
	root := fixture(t)
	expectScope(t, root, nil, "HEAD", false)
	put(t, root, "first_test.go", "package fixture\n")
	expectScope(t, root, nil, "HEAD", false)
	if _, _, err := selectFiles(root, nil, "", false); err == nil {
		t.Fatal("unscoped run succeeded")
	}
	if _, _, err := selectFiles(root, nil, "missing-ref", false); err == nil {
		t.Fatal("invalid base succeeded")
	}
}

func TestInvalidExactPathsFailInsteadOfBroadening(t *testing.T) {
	root := fixture(t)
	put(t, root, "first_test.go", "package fixture\n")
	put(t, root, "generated.go", "// Code generated by fixture. DO NOT EDIT.\npackage fixture\n")
	if err := os.Symlink(filepath.Join(root, "first.go"), filepath.Join(root, "link.go")); err != nil {
		t.Fatal(err)
	}
	for _, name := range []string{"missing.go", "*.go", "go.mod", "first_test.go", "generated.go", "link.go", ".", "../outside.go"} {
		if _, _, err := selectFiles(root, []string{filepath.Join(root, name)}, "HEAD", true); err == nil {
			t.Errorf("accepted invalid explicit path %q", name)
		}
	}
	if _, _, err := selectFiles(root, []string{filepath.Join(root, "first.go"), filepath.Join(root, "missing.go")}, "", false); err == nil {
		t.Fatal("partly invalid selection succeeded")
	}
}

